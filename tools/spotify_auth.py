"""One-time Spotify login (Authorization Code + PKCE, no client secret).

Opens the Spotify consent page, catches the redirect on 127.0.0.1:8888 and
writes main/secrets.h with the Wi-Fi settings, client id and refresh token.

Run:  python tools/spotify_auth.py
"""
import base64
import hashlib
import http.server
import json
import os
import secrets
import threading
import urllib.parse
import urllib.request
import webbrowser

CLIENT_ID = "0cf3326ab8af4902946e2710cdf0d73c"
REDIRECT_URI = "http://127.0.0.1:8888/callback"
SCOPES = "user-read-currently-playing user-read-playback-state"

# Optional developer defaults for main/secrets.h (the setup portal normally replaces these).
# Set WIFI_SSID / WIFI_PASSWORD in the environment, or type them when asked.
WIFI_SSID = os.environ.get("WIFI_SSID") or input("Wi-Fi name for the dev defaults: ").strip()
WIFI_PASSWORD = os.environ.get("WIFI_PASSWORD") or input("Wi-Fi password: ")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "main", "secrets.h")

verifier = base64.urlsafe_b64encode(secrets.token_bytes(64)).rstrip(b"=").decode()
challenge = base64.urlsafe_b64encode(hashlib.sha256(verifier.encode()).digest()).rstrip(b"=").decode()
state = secrets.token_urlsafe(16)

result = {}
done = threading.Event()


class Handler(http.server.BaseHTTPRequestHandler):
    def do_GET(self):
        q = urllib.parse.parse_qs(urllib.parse.urlparse(self.path).query)
        if not self.path.startswith("/callback"):
            self.send_response(404)
            self.end_headers()
            return
        if q.get("state", [""])[0] != state or "code" not in q:
            result["error"] = q.get("error", ["bad state / no code"])[0]
        else:
            result["code"] = q["code"][0]
        self.send_response(200)
        self.send_header("Content-Type", "text/html")
        self.end_headers()
        self.wfile.write(b"<h2>Done - you can close this tab and go back to the terminal.</h2>")
        done.set()

    def log_message(self, *a):
        pass


server = http.server.HTTPServer(("127.0.0.1", 8888), Handler)
threading.Thread(target=server.serve_forever, daemon=True).start()

url = "https://accounts.spotify.com/authorize?" + urllib.parse.urlencode({
    "client_id": CLIENT_ID,
    "response_type": "code",
    "redirect_uri": REDIRECT_URI,
    "scope": SCOPES,
    "state": state,
    "code_challenge_method": "S256",
    "code_challenge": challenge,
})
print("Opening Spotify login in your browser...")
print("If it does not open, visit:\n" + url)
webbrowser.open(url)

if not done.wait(timeout=300):
    raise SystemExit("Timed out waiting for the Spotify redirect.")
server.shutdown()
if "code" not in result:
    raise SystemExit("Authorization failed: " + result.get("error", "unknown"))

data = urllib.parse.urlencode({
    "grant_type": "authorization_code",
    "code": result["code"],
    "redirect_uri": REDIRECT_URI,
    "client_id": CLIENT_ID,
    "code_verifier": verifier,
}).encode()
req = urllib.request.Request("https://accounts.spotify.com/api/token", data=data)
with urllib.request.urlopen(req) as r:
    tok = json.load(r)

refresh = tok["refresh_token"]


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/spotify_auth.py - contains secrets, do not share/commit.\n")
    f.write("#pragma once\n")
    f.write("#define WIFI_SSID " + c_str(WIFI_SSID) + "\n")
    f.write("#define WIFI_PASSWORD " + c_str(WIFI_PASSWORD) + "\n")
    f.write("#define SPOTIFY_CLIENT_ID " + c_str(CLIENT_ID) + "\n")
    f.write("#define SPOTIFY_REFRESH_TOKEN " + c_str(refresh) + "\n")

print("Success. Wrote", OUT)
